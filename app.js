function escHTML(v){
  return String(v).replace(/[&<>"']/g, ch => ({
    "&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#039;"
  }[ch]));
}
function toImageSrc(src){
  // يحول المسار إلى رابط صحيح حتى مع المسافات والأسماء العربية.
  return new URL(encodeURI(String(src).trim()), document.baseURI).href;
}
function renderPortfolio(){
  const gallery = document.getElementById("gallery");
  const filters = document.getElementById("filters");
  gallery.innerHTML = "";
  filters.innerHTML = '<button class="filter active" data-filter="all">الكل</button>';
  // Flatten all images once so the fullscreen viewer can navigate through the
  // currently visible category without changing the original image dimensions.
  const lightboxItems = [];
  Object.entries(PORTFOLIO).forEach(([folderName, folder]) => {
    const filter = document.createElement("button");
    filter.className = "filter";
    filter.dataset.filter = folder.key;
    filter.textContent = folderName;
    filters.appendChild(filter);
    const items = (folder.images || []).map((item) => (
      typeof item === "string"
        ? { src: item, title: item.split("/").pop(), type: folderName }
        : item
    ));
    // Social Media is displayed as groups of exactly four cards.
    // If there are more than four designs, another group is created automatically.
    const isSocial = folder.key === "social";
    const groups = isSocial
      ? Array.from({length: Math.ceil(items.length / 4)}, (_, i) => items.slice(i * 4, i * 4 + 4))
      : [items];
    groups.forEach((group, groupIndex) => {
      if (!group.length) return;
      const groupWrap = document.createElement("div");
      groupWrap.className = isSocial ? "portfolio-social-group" : "portfolio-category-group";
      groupWrap.dataset.cat = folder.key;
      if (isSocial) {
        const title = document.createElement("div");
        title.className = "card-group-title";
        title.textContent = `مجموعة ${groupIndex + 1} — ${group.length} تصاميم`;
        groupWrap.appendChild(title);
      }
      const groupGrid = document.createElement("div");
      groupGrid.className = "card-group";
      group.forEach((data) => {
        const card = document.createElement("article");
        card.className = "card";
        card.dataset.cat = folder.key;
        const workImg = document.createElement("div");
        workImg.className = "work-img";
        const img = document.createElement("img");
        img.src = toImageSrc(data.src);
        img.alt = data.title || folderName;
        img.loading = "lazy";
        img.addEventListener("error", () => {
          workImg.innerHTML = `
            <div style="padding:24px;text-align:center;color:#fff;font-family:inherit">
              <div style="font-size:28px;margin-bottom:8px">⚠️</div>
              <strong style="display:block;margin-bottom:8px">الصورة غير موجودة</strong>
              <small style="display:block;direction:ltr;word-break:break-all;opacity:.7">${escHTML(data.src)}</small>
            </div>`;
        });
        // Keep the source image's natural proportions. No forced 4:3 box.
        workImg.appendChild(img);
        const info = document.createElement("div");
        info.className = "info";
        info.innerHTML = `
          <h3>${escHTML(data.title || "Design")}</h3>
          <span>${escHTML(data.type || folderName)}</span>
        `;
        card.appendChild(workImg);
        card.appendChild(info);
        groupGrid.appendChild(card);
        lightboxItems.push({
          src: toImageSrc(data.src),
          title: data.title || folderName,
          cat: folder.key
        });
      });
      groupWrap.appendChild(groupGrid);
      gallery.appendChild(groupWrap);
    });
  });
  const buttons = filters.querySelectorAll(".filter");
  const groups = gallery.querySelectorAll(".portfolio-social-group,.portfolio-category-group");
  function applyFilter(filter){
    groups.forEach(group => {
      group.style.display = (filter === "all" || group.dataset.cat === filter) ? "" : "none";
    });
  }
  buttons.forEach(btn => {
    btn.addEventListener("click", () => {
      buttons.forEach(b => b.classList.remove("active"));
      btn.classList.add("active");
      applyFilter(btn.dataset.filter);
    });
  });
  // Fullscreen viewer
  const lightbox = document.getElementById("lightbox");
  const lightboxImage = document.getElementById("lightboxImage");
  const closeBtn = document.getElementById("lightboxClose");
  const prevBtn = document.getElementById("lightboxPrev");
  const nextBtn = document.getElementById("lightboxNext");
  let currentIndex = 0;
  function visibleLightboxItems(){
    const active = filters.querySelector(".filter.active")?.dataset.filter || "all";
    return active === "all"
      ? lightboxItems
      : lightboxItems.filter(item => item.cat === active);
  }
  function showLightbox(index){
    const items = visibleLightboxItems();
    if (!items.length) return;
    currentIndex = (index + items.length) % items.length;
    const item = items[currentIndex];
    lightboxImage.src = item.src;
    lightboxImage.alt = item.title;
    lightbox.classList.add("open");
    lightbox.setAttribute("aria-hidden","false");
    document.body.style.overflow = "hidden";
  }
  function closeLightbox(){
    lightbox.classList.remove("open");
    lightbox.setAttribute("aria-hidden","true");
    lightboxImage.removeAttribute("src");
    document.body.style.overflow = "";
  }
  function moveLightbox(step){
    showLightbox(currentIndex + step);
  }
  // Map every card to the correct index in the active viewer.
  groups.forEach(group => {
    group.querySelectorAll(".card").forEach(card => {
      const img = card.querySelector(".work-img img");
      if (!img) return;
      card.addEventListener("click", () => {
        const src = img.src;
        const items = visibleLightboxItems();
        const index = items.findIndex(item => item.src === src);
        if (index >= 0) showLightbox(index);
      });
    });
  });
  closeBtn.addEventListener("click", closeLightbox);
  prevBtn.addEventListener("click", (e) => { e.stopPropagation(); moveLightbox(-1); });
  nextBtn.addEventListener("click", (e) => { e.stopPropagation(); moveLightbox(1); });
  lightbox.addEventListener("click", (e) => {
    if (e.target === lightbox) closeLightbox();
  });
  document.addEventListener("keydown", (e) => {
    if (!lightbox.classList.contains("open")) return;
    if (e.key === "Escape") closeLightbox();
    if (e.key === "ArrowLeft") moveLightbox(1);
    if (e.key === "ArrowRight") moveLightbox(-1);
  });
}
