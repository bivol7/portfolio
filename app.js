function lockIntroPage(){
  document.documentElement.classList.add("intro-page-lock");
  document.body.classList.add("intro-lock");
  document.documentElement.style.overscrollBehavior = "none";
  document.body.style.overscrollBehavior = "none";
}
function unlockIntroPage(){
  document.documentElement.classList.remove("intro-page-lock");
  document.body.classList.remove("intro-lock");
  document.documentElement.style.overscrollBehavior = "";
  document.body.style.overscrollBehavior = "";
}
function closeIntro(){
  if (!siteIntro) return;
  siteIntro.classList.add("is-leaving");
  unlockIntroPage();
}
function showIntro(){
  if (!siteIntro) return;
  siteIntro.style.display = "flex";
  void siteIntro.offsetWidth;
  siteIntro.classList.remove("is-leaving");
  lockIntroPage();
}
function replayIntroAnimations(){
  if (!siteIntro) return;
  const animated = siteIntro.querySelectorAll(".intro-kicker,.intro-frame,.intro-title,.intro-subtitle,.intro-btn,.intro-hint");
  animated.forEach(el => { el.style.animation = "none"; });
  void siteIntro.offsetWidth;
  animated.forEach(el => { el.style.animation = ""; });
}
